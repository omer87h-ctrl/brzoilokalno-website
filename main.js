const LANG_KEY = "bil-lang";
let googlePlayLive = false;

function applySiteConfig() {
  const config = window.SITE_CONFIG || {};

  document.querySelectorAll('[data-store="huawei"]').forEach((btn) => {
    if (config.huaweiAppGallery) {
      btn.href = config.huaweiAppGallery;
    }
  });

  googlePlayLive = Boolean(config.googlePlay && config.googlePlay.trim());
  document.querySelectorAll('[data-store="googlePlay"]').forEach((btn) => {
    if (googlePlayLive) {
      btn.href = config.googlePlay.trim();
      btn.classList.remove("store-btn--soon");
      btn.removeAttribute("aria-disabled");
      btn.setAttribute("target", "_blank");
      btn.setAttribute("rel", "noopener noreferrer");
    } else {
      btn.removeAttribute("href");
      btn.classList.add("store-btn--soon");
      btn.setAttribute("aria-disabled", "true");
    }
  });

  const instagram = config.instagram && config.instagram.trim();
  document.querySelectorAll('[data-social="instagram"]').forEach((link) => {
    if (instagram) {
      link.href = instagram;
      link.classList.remove("is-hidden");
    } else {
      link.classList.add("is-hidden");
    }
  });

  const promoVideoUrl = config.promoVideoUrl && config.promoVideoUrl.trim();
  const videoWrap = document.getElementById("promo-video-wrap");
  const videoIframe = document.getElementById("promo-video-iframe");
  const platformReel = document.getElementById("platform-reel");
  if (promoVideoUrl && videoWrap && videoIframe) {
    videoIframe.src = promoVideoUrl;
    videoWrap.classList.remove("is-hidden");
    if (platformReel) platformReel.classList.add("is-hidden");
  }

  if (config.googleAnalyticsId && config.googleAnalyticsId.trim()) {
    const id = config.googleAnalyticsId.trim();
    const script = document.createElement("script");
    script.async = true;
    script.src = `https://www.googletagmanager.com/gtag/js?id=${id}`;
    document.head.appendChild(script);

    window.dataLayer = window.dataLayer || [];
    function gtag() {
      window.dataLayer.push(arguments);
    }
    window.gtag = gtag;
    gtag("js", new Date());
    gtag("config", id);
  }
}

function setLanguage(lang) {
  const strings = translations[lang] || translations.bs;
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key === "store.playSmall" && googlePlayLive && strings["store.playSmallActive"]) {
      el.textContent = strings["store.playSmallActive"];
      return;
    }
    if (key === "download.text" && googlePlayLive && strings["download.textBoth"]) {
      el.textContent = strings["download.textBoth"];
      return;
    }
    if (strings[key]) {
      el.textContent = strings[key];
    }
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle("active", active);
    btn.setAttribute("aria-pressed", String(active));
  });

  localStorage.setItem(LANG_KEY, lang);
}

document.querySelectorAll(".lang-btn").forEach((btn) => {
  btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
});

const savedLang = localStorage.getItem(LANG_KEY);
applySiteConfig();
setLanguage(savedLang === "en" ? "en" : "bs");

function getShareUrl() {
  const cfg = window.SITE_CONFIG || {};
  return cfg.siteUrl || `${window.location.origin}/`;
}

async function shareSite() {
  const url = getShareUrl();
  const title = "Brzo i Lokalno";
  const text = "Majstori i kreatori u tvom gradu — objavi posao ili pronađi uslugu lokalno.";
  if (navigator.share) {
    try {
      await navigator.share({ title, text, url });
      return;
    } catch (error) {
      if (error?.name === "AbortError") return;
    }
  }
  try {
    await navigator.clipboard.writeText(url);
    alert(`Link kopiran:\n${url}`);
  } catch (_) {
    window.prompt("Kopiraj link:", url);
  }
}

const shareSiteBtn = document.getElementById("share-site-btn");
if (shareSiteBtn) {
  shareSiteBtn.addEventListener("click", () => {
    shareSite();
  });
}

